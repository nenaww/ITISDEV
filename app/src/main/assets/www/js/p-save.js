function findExactSavemorePriceWindow(values, productCount, targetAmount) {
    const target = roundMoney(targetAmount);

    for (let start = 0; start <= values.length - productCount; start++) {
        const windowValues = values.slice(start, start + productCount);
        const sum = roundMoney(windowValues.reduce((total, value) => total + value, 0));

        if (Math.abs(sum - target) < 0.08) {
            return windowValues;
        }
    }

    return [];
}

function findBestSavemorePriceWindow(values, productCount, targetAmount) {
    if (values.length < productCount) return [];

    let bestWindow = [];
    let bestDifference = Infinity;

    for (let start = 0; start <= values.length - productCount; start++) {
        const windowValues = values.slice(start, start + productCount);
        const sum = roundMoney(windowValues.reduce((total, value) => total + value, 0));
        const difference = targetAmount > 0 ? Math.abs(sum - targetAmount) : 0;

        if (difference < bestDifference) {
            bestDifference = difference;
            bestWindow = windowValues;
        }
    }

    if (targetAmount <= 0) {
        return bestWindow;
    }

    const allowedDifference = Math.max(5, targetAmount * 0.03);

    return bestDifference <= allowedDifference ? bestWindow : [];
}

function findOrderedSavemorePriceSubset(values, productCount, targetAmount) {
    if (!targetAmount || targetAmount <= 0) return [];
    if (values.length < productCount) return [];
    if (values.length > 80 || productCount > 60) return [];

    const cents = values.map(value => Math.round(value * 100));
    const targetCents = Math.round(targetAmount * 100);
    const memo = new Map();

    function search(startIndex, neededCount, remainingCents) {
        const key = `${startIndex}-${neededCount}-${remainingCents}`;

        if (memo.has(key)) {
            return memo.get(key);
        }

        if (neededCount === 0) {
            return Math.abs(remainingCents) <= 1 ? [] : null;
        }

        if (startIndex >= cents.length) {
            return null;
        }

        if (cents.length - startIndex < neededCount) {
            return null;
        }

        for (let index = startIndex; index < cents.length; index++) {
            const value = cents[index];

            if (value > remainingCents + 1) {
                continue;
            }

            const result = search(index + 1, neededCount - 1, remainingCents - value);

            if (result) {
                const answer = [index, ...result];
                memo.set(key, answer);
                return answer;
            }
        }

        memo.set(key, null);
        return null;
    }

    const selectedIndexes = search(0, productCount, targetCents);

    if (!selectedIndexes) {
        return [];
    }

    return selectedIndexes.map(index => values[index]);
}

