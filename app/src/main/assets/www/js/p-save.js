function savemoreItemsProbablySame(a, b) {
    return getSavemoreItemMatchScore(a, b) >= 0.74;
}

function getSavemoreItemMatchScore(a, b) {
    const utils = window.ParserUtils;

    const aName = utils.normalizeKey(a.name || a.rawName || "");
    const bName = utils.normalizeKey(b.name || b.rawName || "");
    const aRaw = utils.normalizeKey(a.rawName || a.name || "");
    const bRaw = utils.normalizeKey(b.rawName || b.name || "");

    let score = 0;

    if (aName && bName && aName === bName) score += 0.85;
    if (aName && bName && (aName.includes(bName) || bName.includes(aName))) score += 0.50;

    const nameSimilarity = utils.similarityScore(aName, bName);
    const rawSimilarity = utils.similarityScore(aRaw, bRaw);
    const crossSimilarityA = utils.similarityScore(aName, bRaw);
    const crossSimilarityB = utils.similarityScore(aRaw, bName);

    score += Math.max(nameSimilarity, rawSimilarity, crossSimilarityA, crossSimilarityB) * 0.50;

    if (Number(a.quantity || 1) === Number(b.quantity || 1)) {
        score += 0.15;
    }

    return Math.min(score, 1);
}

