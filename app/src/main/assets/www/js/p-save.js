function normalizeSavemoreLineForParsing(line) {
    return String(line || "")
        .replace(/[₱]/g, "")
        .replace(/[|]/g, "I")
        .replace(/[“”]/g, '"')
        .replace(/[‘’]/g, "'")
        .replace(/^\s*[Iil!jJ]\s*["']\s*(?=[#A-Za-z{])/g, "1 ")
        .replace(/^\s*[Iil!jJ]\s+(?=[#A-Za-z{])/g, "1 ")
        .replace(/^\s*[({\[]\s*(?=[A-Za-z#])/g, "1 ")
        .replace(/^\s*§\s+(?=[A-Za-z#])/g, "5 ")
        .replace(/^\s*S\s+(?=DelMonte|Del\s*Monte|DELMONTE)/i, "5 ")
        .replace(/\s+/g, " ")
        .trim();
}

function hasEndingPriceLoose(line) {
    return /(-?\d{1,3}(?:,\d{3})*[.,]\d{2}|-?\d{1,6}[.,]\d{2})(?:\s*[A-Za-z)]{0,3})?\s*$/.test(String(line || ""));
}

function parseSavemoreQuantity(value) {
    const raw = String(value || "").trim();

    if (/^[Iil!jJ({\[]$/.test(raw)) return 1;
    if (/^§$/.test(raw)) return 5;

    const qty = Number(raw.replace(/[^0-9]/g, ""));

    return !isNaN(qty) && qty > 0 ? qty : 1;
}

