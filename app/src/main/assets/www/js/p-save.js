function matchSavemoreDetailedRule(key) {
    const utils = window.ParserUtils;
    let bestMatch = null;
    let bestScore = 0;

    for (const product of SAVEMORE_DETAIL_RULES) {
        for (const pattern of product.patterns) {
            const patternKey = utils.normalizeKey(pattern);

            if (patternKey.length < 6) continue;

            let score = 0;

            if (key.includes(patternKey)) {
                score = 1;
            } else if (patternKey.includes(key) && key.length >= 8) {
                score = 0.95;
            } else {
                score = utils.slidingSimilarity(key, patternKey);
            }

            if (score > bestScore) {
                bestScore = score;
                bestMatch = product;
            }
        }
    }

    return bestScore >= 0.82 ? bestMatch : null;
}

