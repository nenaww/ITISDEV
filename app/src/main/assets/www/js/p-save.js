function extractSavemorePriceColumn(rawText, productCount, targetAmount) {
    if (!productCount || productCount <= 0) return [];

    const hasDiscount = hasSavemoreDiscountSignal(rawText);

    if (!hasDiscount && targetAmount > 0) {
        const exactPrices = findSavemorePriceColumnByTarget(rawText, productCount, targetAmount);

        if (exactPrices.length === productCount) {
            return exactPrices;
        }
    }

    const candidates = extractSavemoreMoneyCandidates(rawText, targetAmount, productCount);
    const values = candidates.map(item => item.value);

    if (values.length < productCount) {
        return [];
    }

    if (!hasDiscount && targetAmount > 0) {
        const bestWindow = findBestSavemorePriceWindow(values, productCount, targetAmount);

        if (bestWindow.length === productCount) {
            return bestWindow;
        }
    }

    return values.slice(0, productCount);
}

function findSavemorePriceColumnByTarget(rawText, productCount, targetAmount) {
    if (!targetAmount || targetAmount <= 0 || !productCount || productCount <= 0) {
        return [];
    }

    const candidates = extractSavemoreMoneyCandidates(rawText, targetAmount, productCount);
    const values = candidates.map(item => item.value);

    if (values.length < productCount) {
        return [];
    }

    const exactWindow = findExactSavemorePriceWindow(values, productCount, targetAmount);

    if (exactWindow.length === productCount) {
        return exactWindow;
    }

    const subset = findOrderedSavemorePriceSubset(values, productCount, targetAmount);

    if (subset.length === productCount) {
        return subset;
    }

    return [];
}

function extractSavemoreMoneyCandidates(rawText, targetAmount = 0, productCount = 0) {
    const lines = window.ParserUtils.splitReceiptLines(rawText);
    const candidates = [];

    lines.forEach((line, lineIndex) => {
        const cleanLine = String(line || "").trim();
        const upper = cleanLine.toUpperCase();

        if (!cleanLine) return;
        if (isSavemoreFinancialPriceLine(upper)) return;

        const value = extractStandaloneSavemoreMoneyValue(cleanLine);

        if (!value || value <= 0) return;
        if (targetAmount > 0 && value > targetAmount) return;

        if (targetAmount > 0 && productCount > 1 && Math.abs(value - targetAmount) < 0.08) {
            return;
        }

        candidates.push({
            value: roundMoney(value),
            line: cleanLine,
            lineIndex
        });
    });

    return candidates;
}

function extractStandaloneSavemoreMoneyValue(line) {
    const clean = String(line || "")
        .trim()
        .replace(/[₱]/g, "")
        .replace(/^PHP\s+/i, "")
        .trim();

    if (!clean) return 0;

    const repaired = window.ParserUtils &&
        typeof window.ParserUtils.repairOcrMoneyText === "function"
        ? window.ParserUtils.repairOcrMoneyText(clean)
        : clean
            .replace(/[OoQqDd]/g, "0")
            .replace(/[IiLl!|]/g, "1")
            .replace(/[SsEe]/g, "5")
            .replace(/[Bb]/g, "8")
            .replace(/[Gg]/g, "6")
            .replace(/[Zz]/g, "2");

    const valid =
        /^-?\d{1,3}(?:,\d{3})*[.,]\d{2}$/.test(repaired) ||
        /^-?\d{1,8}[.,]\d{2}$/.test(repaired);

    if (!valid) return 0;

    return parseSavemoreMoney(repaired);
}

function parseSavemoreMoney(value) {
    let text = "";

    if (
        window.ParserUtils &&
        typeof window.ParserUtils.repairOcrMoneyText === "function"
    ) {
        text = window.ParserUtils.repairOcrMoneyText(value);
    } else {
        text = String(value || "")
            .trim()
            .replace(/[₱\s]/g, "")
            .replace(/[OoQqDd]/g, "0")
            .replace(/[IiLl!|]/g, "1")
            .replace(/[SsEe]/g, "5")
            .replace(/[Bb]/g, "8")
            .replace(/[Gg]/g, "6")
            .replace(/[Zz]/g, "2");
    }

    if (!text) return 0;

    const commaCount = (text.match(/,/g) || []).length;
    const dotCount = (text.match(/\./g) || []).length;

    if (commaCount > 1 && dotCount === 0) {
        const lastCommaIndex = text.lastIndexOf(",");
        const wholePart = text.slice(0, lastCommaIndex).replace(/,/g, "");
        const decimalPart = text.slice(lastCommaIndex + 1);

        text = `${wholePart}.${decimalPart}`;
    } else if (commaCount >= 1 && dotCount >= 1) {
        text = text.replace(/,/g, "");
    } else if (commaCount === 1 && dotCount === 0) {
        text = text.replace(",", ".");
    }

    const number = Number(text);

    return Number.isFinite(number) ? roundMoney(number) : 0;
}

